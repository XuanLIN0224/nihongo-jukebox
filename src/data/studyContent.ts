function levelFromTags(word: StudyWord): JLPTLevel {
  const tag = word.tags.find((item) => /^jlpt-n[1-5]$/i.test(item));
  return tag ? (`N${tag.slice(-1)}` as JLPTLevel) : "N3";
}

