import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import kuromoji from "kuromoji";
import * as wanakana from "wanakana";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const studyContentPath = path.join(rootDir, "src/data/studyContent.ts");
const generatedVocabularyPath = path.join(rootDir, "src/data/generatedVocabulary.json");
const lyricVocabularyPath = path.join(rootDir, "src/data/lyricVocabulary.ts");
const outputPath = path.join(rootDir, "src/data/exampleReadings.ts");

const latinPattern = /^[A-Za-z0-9][A-Za-z0-9'’&.+-]*$/;
const kanaPattern = /^[ぁ-んァ-ンー]+$/;
const punctuationPattern = /^[\s、。．，,!?！？…・「」『』（）()［］\[\]【】〈〉《》“”"':：;；〜~♪]+$/u;

function buildTokenizer() {
  return new Promise((resolve, reject) => {
    kuromoji
      .builder({ dicPath: path.join(rootDir, "node_modules/kuromoji/dict") })
      .build((error, tokenizer) => {
        if (error) reject(error);
        else resolve(tokenizer);
      });
  });
}

function toHiragana(value) {
  if (!value || value === "*") return "";
  if (latinPattern.test(value)) return value;
  return wanakana.toHiragana(value);
}

function readingForToken(token) {
  const surface = token.surface_form;
  if (latinPattern.test(surface)) return surface;
  if (token.pos === "助詞" && surface === "は") return "わ";
  if (token.pos === "助詞" && surface === "へ") return "え";
  if (token.pos === "助詞" && surface === "を") return "を";
  const reading = toHiragana(token.reading || token.pronunciation);
  if (reading) return reading;
  if (kanaPattern.test(surface)) return wanakana.toHiragana(surface);
  return surface;
}

function romajiForToken(token, reading) {
  const surface = token.surface_form;
  if (latinPattern.test(surface)) return surface;
  if (token.pos === "助詞" && surface === "は") return "wa";
  if (token.pos === "助詞" && surface === "へ") return "e";
  if (token.pos === "助詞" && surface === "を") return "o";
  return wanakana.toRomaji(reading);
}

function shouldKeepToken(token) {
  const surface = token.surface_form.trim();
  if (!surface) return false;
  if (token.pos === "記号") return false;
  return !punctuationPattern.test(surface);
}

function exampleReading(sentence, tokenizer) {
  const tokens = tokenizer.tokenize(sentence).filter(shouldKeepToken);
  const kana = [];
  const romaji = [];
  for (const token of tokens) {
    const reading = readingForToken(token);
    kana.push(reading);
    romaji.push(romajiForToken(token, reading));
  }
  return {
    kana: kana.join(" "),
    romaji: romaji.join(" ")
  };
}

function loadCuratedAndGrammarExamples() {
  const source = fs.readFileSync(studyContentPath, "utf8");
  const examples = [];
  const objectPattern = /\{\s*id:\s*"([^"]+)"[\s\S]*?exampleJp:\s*"([^"]+)"/g;
  for (const match of source.matchAll(objectPattern)) {
    examples.push({ id: match[1], exampleJp: match[2] });
  }
  return examples;
}

function loadLyricVocabularyExamples() {
  const source = fs.readFileSync(lyricVocabularyPath, "utf8");
  const match = source.match(/export const lyricVocabulary: StudyWord\[\] = ([\s\S]*);\s*$/);
  if (!match) {
    throw new Error("Could not parse lyricVocabulary from src/data/lyricVocabulary.ts");
  }
  return JSON.parse(match[1]).map((word) => ({
    id: word.id,
    exampleJp: word.exampleJp
  }));
}

function loadGeneratedVocabularyExamples() {
  return JSON.parse(fs.readFileSync(generatedVocabularyPath, "utf8")).map((word) => ({
    id: word.id,
    exampleJp: word.exampleJp
  }));
}

function loadExamples() {
  const byId = new Map();
  for (const example of [
    ...loadGeneratedVocabularyExamples(),
    ...loadLyricVocabularyExamples(),
    ...loadCuratedAndGrammarExamples()
  ]) {
    if (example.id && example.exampleJp) byId.set(example.id, example.exampleJp);
  }
  return Array.from(byId.entries()).map(([id, exampleJp]) => ({ id, exampleJp }));
}

const tokenizer = await buildTokenizer();
const entries = loadExamples()
  .map(({ id, exampleJp }) => [id, exampleReading(exampleJp, tokenizer)])
  .sort(([a], [b]) => a.localeCompare(b));

const output = `// Generated by scripts/generate-example-readings.mjs.\n// Kana and romaji annotations for vocabulary example sentences.\n\nexport interface ExampleReading {\n  kana: string;\n  romaji: string;\n}\n\nexport const exampleReadings: Record<string, ExampleReading> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;

fs.writeFileSync(outputPath, output);
console.log(`Generated example readings for ${entries.length} examples.`);
